def get_workflow_artifact_contract(project_path: str | Path, node_id: str) -> dict:
    """Resolve one workflow artifact contract to absolute paths."""
    root = Path(project_path)
    raw = WORKFLOW_ARTIFACT_CONTRACT.get(node_id, {})
    return {
        "primary": str(root / raw["primary"]) if raw.get("primary") else str(root),
        "required": [str(root / path) for path in raw.get("required", ())],
    }

