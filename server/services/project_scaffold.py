def _validate_scaffold_target(root: Path, mode: str) -> None:
    if mode not in {"create", "ensure"}:
        raise ValueError(f"Unsupported scaffold mode: {mode}")
    if mode != "create" or not root.exists():
        return
    if not root.is_dir():
        raise ProjectScaffoldConflict(f"项目路径已存在且不是文件夹：{root}")
    existing = list(root.iterdir())
    if existing:
        preview = ", ".join(entry.name for entry in existing[:5])
        suffix = " ..." if len(existing) > 5 else ""
        raise ProjectScaffoldConflict(
            f"新建项目要求目标目录为空。所选路径已经包含：{preview}{suffix}。"
            "请换一个项目名称，或使用“打开项目”继续已有项目。"
        )


def _create_project_structure(root: Path) -> tuple[list[str], list[str]]:
    directories: list[str] = []
    files: list[str] = []
    for directory_name, info in PROJECT_STRUCTURE.items():
        directory = root / directory_name
        directory.mkdir(exist_ok=True)
        directories.append(directory_name)
        for child_name in info.get("children", {}):
            (directory / child_name).mkdir(exist_ok=True)
            directories.append(f"{directory_name}/{child_name}")
        for filename, content in info.get("files", {}).items():
            path = directory / filename
            if not path.exists():
                atomic_write_text(path, content)
                files.append(f"{directory_name}/{filename}")
    merak = root / ".merak"
    merak.mkdir(exist_ok=True)
    (merak / "wiki").mkdir(exist_ok=True)
    directories.append(".merak")
    return directories, files


def _write_project_metadata(
    root: Path,
    name: str,
    direction: str,
    venue: str,
) -> list[str]:
    created: list[str] = []
    profile = root / "MERAK_PROJECT.md"
    if not profile.exists():
        atomic_write_text(profile, f"""# MERAK Project Configuration

## Project
- name: {name}
- research_direction: {direction or "TBD"}
- target_venue: {venue}
- language: auto

## Experiment Runtime
- gpu: none
- code_sync: rsync
- wandb: false

## Paper Library
- path:

## Pipeline Status
- status: initialized
""")
        created.append("MERAK_PROJECT.md")
    readme = root / "README.md"
    if not readme.exists():
        atomic_write_text(readme, f"""# {name}

## Research Direction
{direction or "TBD"}

## Target Venue
{venue}

## Project Structure
`literature/`, `ideas/`, `experiments/`, `paper/`, `figures/`, `slides/`, and `.merak/`.

## Quick Start
Open the project in Merak, configure the workflow, then explicitly choose whether scientific execution is authorized.
""")
        created.append("README.md")
    return created


def _write_research_templates(
    root: Path,
    name: str,
    direction: str,
    venue: str,
) -> list[str]:
    created: list[str] = []
    for relative, content in research_templates(name, direction, venue).items():
        path = root / relative
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write_text(path, content)
            created.append(relative)
    return created


def _scaffold_paper(root: Path, name: str, direction: str, venue: str) -> list[str]:
    if not venue:
        return []
    from .paper_compiler import VENUE_MAIN_TEX, scaffold_paper_files

    venue_key = re.sub(r"[^a-z0-9]+", "_", venue.casefold()).strip("_")
    venue_key = {"acmmm": "acm_mm", "acm_multimedia": "acm_mm"}.get(
        venue_key, venue_key
    )
    template_venue = venue_key if venue_key in VENUE_MAIN_TEX else "iclr"
    result = scaffold_paper_files(
        str(root / "paper"), template_venue, name,
        abstract=f"Research direction: {direction.strip()}" if direction.strip() else "Your abstract here.",
        overwrite_main=False,
    )
    if not result.get("success"):
        raise ValueError(str(result.get("message") or "Paper scaffold failed"))
    if template_venue != venue_key:
        logger.info(
            "Custom venue uses fallback initial paper scaffold",
            target_venue=venue,
            scaffold_template=template_venue,
        )
    return [f"paper/{relative}" for relative in result.get("files_created", [])]

def scaffold_project(
    project_path: str | Path,
    name: str = "Untitled Research",
    venue: str = "ICLR",
    direction: str = "",
    mode: str = "ensure",
) -> dict:
    """Create or safely complete the canonical research project structure."""

    root = Path(project_path)
    _validate_scaffold_target(root, mode)
    root.mkdir(parents=True, exist_ok=True)
    directories, files = _create_project_structure(root)
    files.extend(_write_project_metadata(root, name, direction, venue))
    files.extend(_write_research_templates(root, name, direction, venue))
    files.extend(_scaffold_paper(root, name, direction, venue))
    logger.info(
        "Project scaffolded",
        path=str(root),
        dirs=len(directories),
        files=len(files),
    )
    return {
        "success": True,
        "path": str(root),
        "name": name,
        "mode": mode,
        "dirs_created": directories,
        "files_created": files,
    }


