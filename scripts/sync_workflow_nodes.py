"""Generate/check frontend workflow metadata without importing runtime services."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from server.contracts.workflow_nodes import WORKFLOW_NODES


def main() -> None:
    target = ROOT / "shared/workflow-nodes.ts"
    source = "// Generated by scripts/sync_workflow_nodes.py; edit server/contracts/workflow_nodes.py.\n"
    source += "export const WORKFLOW_NODES = " + json.dumps(WORKFLOW_NODES, ensure_ascii=False, indent=2) + " as const\n"
    source += "export type WorkflowNodeId = typeof WORKFLOW_NODES[number]['id']\n"
    if "--check" in sys.argv:
        if not target.is_file() or target.read_text(encoding="utf-8") != source:
            raise SystemExit("Workflow metadata differs; run python scripts/sync_workflow_nodes.py")
    else:
        target.write_text(source, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
